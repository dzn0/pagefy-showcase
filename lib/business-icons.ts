// Tipo sem entrada própria: pelo pedaço do nome.
const BY_SUFFIX: Array<[RegExp, LucideIcon]> = [
  [/_restaurant$/, UtensilsCrossed],
  [/_school$/, GraduationCap],
  [/_(clinic|center)$/, Stethoscope],
  [/_store$|_shop$/, Store],
  [/_agency$|_office$/, Briefcase],
];

