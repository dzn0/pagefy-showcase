export function businessIcon(business: { type?: string | null; category: { id: string } }): LucideIcon {
  const type = business.type;
  if (type) {
    const exact = BY_TYPE[type];
    if (exact) return exact;
    const partial = BY_SUFFIX.find(([pattern]) => pattern.test(type));
    if (partial) return partial[1];
  }
  return BY_CATEGORY[business.category.id] ?? Store;
}
